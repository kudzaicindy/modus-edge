function toneFrom(part) {
  const text = String(part || "")
    .toLowerCase()
    .trim()
    // "Silver 2", "Navy 3" → keep the colour word for swatches
    .replace(/\s+\d+$/g, "")
    .replace(/\s+/g, " ");
  if (!text || text === "as shown" || text === "default") return null;
  const keys = Object.keys(TONE).sort((a, b) => b.length - a.length);
  const key = keys.find((item) => {
    if (text === item) return true;
    if (item.includes(" ")) return text.includes(item);
    return text.split(/\s+/).includes(item);
  });
  return key ? TONE[key] : null;
}

export function swatchTones(name = "") {
  const parts = String(name)
    .split("/")
    .map((part) => part.trim())
    .filter(Boolean);
  const tones = parts.map((part) => toneFrom(part)).filter(Boolean);
  return tones.length ? tones : ["#8a93a0"];
}

export function isPaintedColor(name = "") {
  return String(name)
    .split("/")
    .some((part) => toneFrom(part.trim()));
}

export function swatchStyle(name) {
  const tones = swatchTones(name);
  if (tones.length > 1) {
    return { backgroundImage: `linear-gradient(135deg, ${tones[0]} 49%, ${tones[1]} 50%)` };
  }
  return { backgroundColor: tones[0] };
}

export function swatchIsLight(name) {
  const hex = swatchTones(name)[0].replace("#", "");
  if (hex.length !== 6) return true;
  const r = parseInt(hex.slice(0, 2), 16);
  const g = parseInt(hex.slice(2, 4), 16);
  const b = parseInt(hex.slice(4, 6), 16);
  return (r * 299 + g * 587 + b * 114) / 1000 > 200;
}

